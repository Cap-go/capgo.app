-- Canceled-org retention lifecycle:
--   85 days: warn that bundles will be deleted in 5 days (Bento / tracking)
--   90 days: soft-delete bundles (existing) + warn that apps will be deleted in 5 days
--   95 days: delete apps and archive app_id + creator email into old_apps
--
-- Alerts are queued to pgmq and delivered by the canceled_org_retention_alerts
-- edge trigger. Dedup uses public.notifications once-claims so daily cron
-- catch-up does not re-queue forever.

-- Permanent archive of apps removed by the 95-day unpaid retention path.
CREATE TABLE IF NOT EXISTS public.old_apps (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id character varying NOT NULL,
  email text NOT NULL,
  owner_org uuid NOT NULL,
  user_id uuid,
  app_created_at timestamp with time zone,
  deleted_at timestamp with time zone DEFAULT now() NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT old_apps_app_id_owner_org_key UNIQUE (app_id, owner_org)
);

ALTER TABLE public.old_apps OWNER TO postgres;

COMMENT ON TABLE public.old_apps IS
  'Archive of apps deleted after the unpaid/canceled retention window (95 days). Keeps app_id and creator email for support memory; not purged by delete_old_deleted_apps.';

COMMENT ON COLUMN public.old_apps.email IS
  'Email of the app creator (public.users via apps.user_id), falling back to org management_email.';

COMMENT ON COLUMN public.old_apps.app_created_at IS
  'Original apps.created_at at archival time.';

CREATE INDEX IF NOT EXISTS old_apps_email_idx
  ON public.old_apps (email);

CREATE INDEX IF NOT EXISTS old_apps_deleted_at_idx
  ON public.old_apps (deleted_at);

ALTER TABLE public.old_apps ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Deny all access on old_apps" ON public.old_apps;
CREATE POLICY "Deny all access on old_apps"
  ON public.old_apps
  USING (false)
  WITH CHECK (false);

GRANT SELECT, INSERT, REFERENCES, DELETE, TRIGGER, TRUNCATE, UPDATE ON TABLE public.old_apps TO anon;
GRANT SELECT, INSERT, REFERENCES, DELETE, TRIGGER, TRUNCATE, UPDATE ON TABLE public.old_apps TO authenticated;
GRANT ALL ON TABLE public.old_apps TO service_role;
GRANT ALL ON SEQUENCE public.old_apps_id_seq TO anon;
GRANT ALL ON SEQUENCE public.old_apps_id_seq TO authenticated;
GRANT ALL ON SEQUENCE public.old_apps_id_seq TO service_role;

-- Parameterized eligibility: canceled/deleted orgs past N days of end-of-access.
CREATE OR REPLACE FUNCTION public.canceled_org_ids_past_grace(p_days integer)
RETURNS SETOF uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT o.id
  FROM public.stripe_info AS si
  JOIN public.orgs AS o ON o.customer_id = si.customer_id
  WHERE si.status IN ('canceled', 'deleted')
    AND GREATEST(si.canceled_at, si.subscription_anchor_end, si.trial_at)
      <= pg_catalog.now() - make_interval(days => GREATEST(0, COALESCE(p_days, 0)));
$$;

ALTER FUNCTION public.canceled_org_ids_past_grace(integer) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.canceled_org_ids_past_grace(integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.canceled_org_ids_past_grace(integer) FROM anon;
REVOKE ALL ON FUNCTION public.canceled_org_ids_past_grace(integer) FROM authenticated;
GRANT ALL ON FUNCTION public.canceled_org_ids_past_grace(integer) TO service_role;

COMMENT ON FUNCTION public.canceled_org_ids_past_grace(integer) IS
  'Org ids whose stripe_info is canceled/deleted and GREATEST(canceled_at, subscription_anchor_end, trial_at) is older than p_days.';

-- Keep the existing 90-day helper as a thin wrapper for call sites / tests.
