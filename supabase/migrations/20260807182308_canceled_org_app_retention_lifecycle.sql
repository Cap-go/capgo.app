REVOKE ALL ON FUNCTION public.cleanup_long_canceled_org_data() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cleanup_long_canceled_org_data() FROM anon;
REVOKE ALL ON FUNCTION public.cleanup_long_canceled_org_data() FROM authenticated;
GRANT ALL ON FUNCTION public.cleanup_long_canceled_org_data() TO service_role;

COMMENT ON FUNCTION public.cleanup_long_canceled_org_data() IS
  'Daily canceled-org retention: 85d bundle warning, 90d soft-delete versions + app warning, 95d delete apps into old_apps, then purge audit_logs. Steps are batch/runtime bounded.';

-- Alert delivery queue + high-frequency drain registration.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pgmq.list_queues()
    WHERE queue_name = 'canceled_org_retention_alerts'
  ) THEN
    PERFORM pgmq.create('canceled_org_retention_alerts');
  END IF;
END;
$$;

DO $$
DECLARE
  high_frequency_task_type public.cron_task_type;
  high_frequency_target jsonb;
BEGIN
  SELECT cron.task_type, cron.target::jsonb
  INTO high_frequency_task_type, high_frequency_target
  FROM public.cron_tasks AS cron
  WHERE cron.name = 'high_frequency_queues'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Required cron task high_frequency_queues is missing';
  END IF;

  IF high_frequency_task_type
    IS DISTINCT FROM 'function_queue'::public.cron_task_type THEN
    RAISE EXCEPTION 'Cron task high_frequency_queues must use task type function_queue';
  END IF;

  IF pg_catalog.jsonb_typeof(high_frequency_target)
    IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Cron task high_frequency_queues target must be a JSON array';
  END IF;

  IF NOT (high_frequency_target ? 'canceled_org_retention_alerts') THEN
    UPDATE public.cron_tasks
    SET
      target = (
        high_frequency_target || '["canceled_org_retention_alerts"]'::jsonb
      )::text,
      updated_at = pg_catalog.now()
    WHERE name = 'high_frequency_queues';
  END IF;
END;
$$;

UPDATE public.cron_tasks
SET
  description = 'Canceled-org retention: 85d bundle warn, 90d soft-delete + app warn, 95d delete apps into old_apps, purge audit logs',
  updated_at = now()
WHERE name = 'canceled_org_version_cleanup';
