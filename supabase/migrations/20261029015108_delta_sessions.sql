-- Upload sessions out of delta_files. Encrypted uploads put a session (hex,
-- up to ~470 characters) in every file path of the upload, so a 5,000-file
-- bundle stored the same ~370 bytes 5,000 times: about 2M rows share 3.8k
-- sessions, 700 MB of the table. A row now points to its session:
--
--   session = COALESCE(delta_files.path_session, delta_sessions.session)
--   delta_sessions.id = delta_files.path_session_id
--
-- Rollout: this migration adds the table, the readers and a task that does
-- nothing until CAPGO_DELTA_SESSIONS_ENABLED is set, after every worker
-- reading delta_files runs this release (the previous workers, and their
-- plugin reads on the replicas, read path_session directly). The task then
-- moves the existing sessions in about 3 hours, and compaction moves the
-- session of every new row.

SET lock_timeout = '5s';

-- Sessions are never shared across apps; rows go with their app, like
-- delta_files.
CREATE TABLE public.delta_sessions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id character varying NOT NULL REFERENCES public.apps (
        app_id
    ) ON DELETE CASCADE,
    session bytea NOT NULL -- noqa: RF04
);
COMMENT ON TABLE public.delta_sessions IS
'Upload session bytes, referenced by delta_files.path_session_id.';
-- Writes only; the replicas read by primary key.
CREATE UNIQUE INDEX delta_sessions_app_id_session_idx ON public.delta_sessions (
    app_id, session
);

ALTER TABLE public.delta_sessions OWNER TO postgres;
ALTER TABLE public.delta_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.delta_sessions FROM public, anon, authenticated;
GRANT SELECT ON TABLE public.delta_sessions TO anon, authenticated;
GRANT ALL ON TABLE public.delta_sessions TO service_role;

-- Same scope as delta_files: whoever reads a row reads its session.
CREATE POLICY delta_sessions_read ON public.delta_sessions
FOR SELECT TO anon, authenticated
USING (
    app_id
    = ANY(
        COALESCE(
            (SELECT public.app_versions_readable_app_ids()),
            '{}'::character varying[]
        )
    )
);
CREATE POLICY delta_sessions_no_insert ON public.delta_sessions AS RESTRICTIVE
FOR INSERT TO anon, authenticated WITH CHECK (false);
CREATE POLICY delta_sessions_no_update ON public.delta_sessions AS RESTRICTIVE
FOR UPDATE TO anon, authenticated USING (false) WITH CHECK (false);
CREATE POLICY delta_sessions_no_delete ON public.delta_sessions AS RESTRICTIVE
FOR DELETE TO anon, authenticated USING (false);

-- No foreign key: the replicas have none, and sessions are only removed with
-- their app (which removes its delta_files rows too).
ALTER TABLE public.delta_files ADD COLUMN path_session_id integer;

-- Plugin reads run on read replicas: publish the new table to the Google
-- subscriber. Rows only flow after the subscriber refreshes its subscription.
DO $$
DECLARE
  publication_name text;
BEGIN
  FOR publication_name IN
    SELECT pubname
    FROM pg_catalog.pg_publication
    WHERE pubname IN ('capgo_google_eu_2_pub', 'capgo_google_replicate')
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_publication_tables
      WHERE pubname = publication_name
        AND schemaname = 'public'
        AND tablename = 'delta_sessions'
    ) THEN
      EXECUTE pg_catalog.format('ALTER PUBLICATION %I ADD TABLE public.delta_sessions', publication_name);
    END IF;
  END LOOP;
END;
$$;

-- Moves the sessions of the given rows to delta_sessions. Returns the number
-- of rows rewritten.
CREATE FUNCTION public.delta_sessions_attach(p_ids bigint[])
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_updated integer;
BEGIN
  INSERT INTO public.delta_sessions (app_id, session)
  SELECT DISTINCT df.app_id, df.path_session
  FROM public.delta_files AS df
  WHERE df.id = ANY (p_ids) AND df.path_session IS NOT NULL
  ORDER BY df.app_id, df.path_session
  ON CONFLICT (app_id, session) DO NOTHING;

  UPDATE public.delta_files AS df
  SET path_session_id = ds.id, path_session = NULL
  FROM public.delta_sessions AS ds
  WHERE df.id = ANY (p_ids)
    AND df.path_session IS NOT NULL
    AND ds.app_id = df.app_id
    AND ds.session = df.path_session;
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  RETURN v_updated;
END;
$$;
ALTER FUNCTION public.delta_sessions_attach(bigint[]) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.delta_sessions_attach(bigint[]) FROM public,
anon,
authenticated;
GRANT EXECUTE ON FUNCTION public.delta_sessions_attach(
    bigint[]
) TO service_role;

-- Walks delta_files in id order and moves the sessions of rows compacted
-- before the switch. The cursor lives in backfill_progress. Rows compacted
-- after the switch get their session moved by delta_files_compact.
CREATE FUNCTION public.delta_sessions_move(p_batch_size integer DEFAULT 5000)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_cursor bigint;
  v_ids bigint[];
  v_updated integer;
BEGIN
  IF NOT public.delta_storage_setting('CAPGO_DELTA_SESSIONS_ENABLED', false) THEN
    RETURN 0;
  END IF;

  INSERT INTO public.backfill_progress (job_name, scope_key, cutover_at, last_processed_id)
  VALUES ('delta_sessions_move', 'all', now(), 0)
  ON CONFLICT (job_name, scope_key) DO NOTHING;

  -- One run at a time.
  SELECT bp.last_processed_id INTO v_cursor
  FROM public.backfill_progress AS bp
  WHERE bp.job_name = 'delta_sessions_move' AND bp.scope_key = 'all'
  FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN
    RETURN 0;
  END IF;

  SELECT pg_catalog.array_agg(batch.id ORDER BY batch.id) INTO v_ids
  FROM (
    SELECT df.id
    FROM public.delta_files AS df
    WHERE df.id > COALESCE(v_cursor, 0)
    ORDER BY df.id
    LIMIT GREATEST(COALESCE(p_batch_size, 5000), 1)
  ) AS batch;
  IF v_ids IS NULL THEN
    RETURN 0;
  END IF;

  v_updated := public.delta_sessions_attach(v_ids);

  UPDATE public.backfill_progress
  SET last_processed_id = v_ids[pg_catalog.cardinality(v_ids)], updated_at = now()
  WHERE job_name = 'delta_sessions_move' AND scope_key = 'all';

  RETURN v_updated;
END;
$$;
ALTER FUNCTION public.delta_sessions_move(integer) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.delta_sessions_move(integer) FROM public,
anon,
authenticated;
GRANT EXECUTE ON FUNCTION public.delta_sessions_move(integer) TO service_role;

