-- Delta storage v2, step 1 of 2: create delta_files / version_files and fill
-- them from every legacy public.manifest row, in batches of versions.
--
-- This step only reads app_versions and public.manifest, so uploads keep
-- running while it copies millions of rows. Foreign keys, triggers, RLS and
-- the switch from the manifest table to a compatibility view happen in the
-- next migration (delta_storage_v2), which also converts versions uploaded
-- while this one ran.

-- Copying every row takes minutes at production scale.
SET statement_timeout = 0;
SET lock_timeout = '5s';

-- One transaction: the copy is all or nothing, and the keyed temp table lives
-- until COMMIT.
BEGIN;

-- The key functions are plpgsql on purpose: on PostgreSQL 17 a non-inlined
-- SQL-language function called once per row keeps about 1 kB per call until
-- the statement ends, which would exhaust memory over millions of rows.
CREATE FUNCTION public.delta_entry_key(p_s3_path text, p_file_name text, p_file_hash text)
RETURNS bytea
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
SET search_path = ''
AS $$
BEGIN
  RETURN pg_catalog.sha256(pg_catalog.convert_to(pg_catalog.json_build_array(p_s3_path, p_file_name, p_file_hash)::text, 'UTF8'));
END;
$$;
ALTER FUNCTION public.delta_entry_key(text, text, text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.delta_entry_key(text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.delta_entry_key(text, text, text) TO service_role;

-- One R2 object can be stored under several spellings of its path: a
-- leading-dot segment as "." or "%2E"/"%2e", percent-encoded, re-encoded
-- ("%2540") or decoded names, partially encoded ones. /files/read moves
-- between them by encoding or decoding segments, so references are matched
-- on the path decoded until it no longer changes: every spelling it accepts
-- reaches the same text. Matching a few more spellings only keeps more files.
--
-- PARALLEL RESTRICTED, not SAFE: on PostgreSQL 17, once the EXCEPTION branch
-- has run inside a parallel worker, later calls in that worker return the
-- path undecoded, so a parallel scan would store wrong path keys.
CREATE FUNCTION public.delta_canonical_path(p_s3_path text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
PARALLEL RESTRICTED
SET search_path = ''
AS $$
DECLARE
  v_path text := p_s3_path;
  v_next text;
BEGIN
  FOR i IN 1..16 LOOP
    EXIT WHEN v_path IS NULL OR pg_catalog.strpos(v_path, '%') = 0;
    BEGIN
      v_next := pg_catalog.convert_from(
        (
          SELECT pg_catalog.string_agg(
            CASE WHEN part.m[1] IS NOT NULL THEN pg_catalog.decode(part.m[1], 'hex') ELSE pg_catalog.convert_to(part.m[2], 'UTF8') END,
            ''::bytea ORDER BY part.ord
          )
          FROM pg_catalog.regexp_matches(v_path, '%([0-9A-Fa-f]{2})|([^%]+|%)', 'g') WITH ORDINALITY AS part (m, ord)
        ),
        'UTF8'
      );
    EXCEPTION WHEN others THEN
      -- Not valid UTF-8 once decoded: only the dotfile escape still resolves.
      RETURN pg_catalog.regexp_replace(v_path, '%2[Ee]', '.', 'g');
    END;
    EXIT WHEN v_next = v_path;
    v_path := v_next;
  END LOOP;
  RETURN v_path;
END;
$$;
ALTER FUNCTION public.delta_canonical_path(text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.delta_canonical_path(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.delta_canonical_path(text) TO service_role;

-- Same key for every spelling of one object (delta_canonical_path), and
-- PARALLEL RESTRICTED for the same reason.
CREATE FUNCTION public.delta_path_key(p_s3_path text)
RETURNS bytea
LANGUAGE plpgsql
IMMUTABLE
PARALLEL RESTRICTED
SET search_path = ''
AS $$
BEGIN
  RETURN pg_catalog.sha256(pg_catalog.convert_to(public.delta_canonical_path(p_s3_path), 'UTF8'));
END;
$$;
ALTER FUNCTION public.delta_path_key(text) OWNER TO postgres;
REVOKE ALL ON FUNCTION public.delta_path_key(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.delta_path_key(text) TO service_role;

CREATE TABLE public.delta_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id character varying NOT NULL,
  s3_path character varying NOT NULL,
  file_name character varying NOT NULL,
  file_hash character varying NOT NULL,
  file_size bigint NOT NULL DEFAULT 0,
  -- sha256 of the canonical path (delta_path_key): every spelling of one object.
  path_key bytea NOT NULL,
  -- sha256 of the (s3_path, file_name, file_hash) triple: dedupe key.
  entry_key bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.delta_files IS
  'One row per unique delta (manifest) file entry. Versions reference rows through version_files.file_ids.';

CREATE TABLE public.version_files (
  app_version_id bigint PRIMARY KEY,
  file_ids bigint[] NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.version_files IS
  'One row per version with its ordered delta_files ids. Written once per upload and never rewritten.';

-- Locked down from the start: default privileges would expose the copied rows
-- through the API until delta_storage_v2 adds the read policies.
ALTER TABLE public.delta_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.version_files ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.delta_files FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.version_files FROM PUBLIC, anon, authenticated;

-- The copy runs in batches of versions inside one DO block, with a NOTICE per
-- batch. A single multi-minute statement sends nothing to the client while it
-- runs, and the deploy runner's connection to the pooler is dropped after
-- about 4 idle minutes (first production attempt: reset after 261 s on 9.7M
-- rows). Each batch is a few short statements, and statement-level memory is
-- freed between them.
CREATE UNIQUE INDEX delta_files_entry_key_idx ON public.delta_files (entry_key);

-- Keys are computed once per legacy row of the current batch.
CREATE TEMP TABLE delta_backfill (
  id bigint NOT NULL,
  app_version_id bigint NOT NULL,
  app_id character varying NOT NULL,
  s3_path character varying NOT NULL,
  file_name character varying NOT NULL,
  file_hash character varying NOT NULL,
  file_size bigint NOT NULL,
  path_key bytea NOT NULL,
  entry_key bytea NOT NULL
) ON COMMIT DROP;

DO $$
DECLARE
  v_version_ids bigint[];
  v_batch bigint[];
  v_batch_size constant integer := 50;
  v_total integer;
  v_rows bigint := 0;
  v_batch_rows bigint;
  v_started timestamptz := pg_catalog.clock_timestamp();
BEGIN
  SELECT pg_catalog.array_agg(av.id ORDER BY av.id)
  INTO v_version_ids
  FROM public.app_versions AS av
  WHERE EXISTS (SELECT 1 FROM public.manifest AS m WHERE m.app_version_id = av.id);
  v_total := COALESCE(pg_catalog.cardinality(v_version_ids), 0);
  RAISE NOTICE 'delta storage backfill: % versions with manifest rows', v_total;

  FOR v_offset IN 0 .. v_total - 1 BY v_batch_size LOOP
    v_batch := v_version_ids[v_offset + 1 : v_offset + v_batch_size];

    -- Created in this transaction, so TRUNCATE empties it in place.
    TRUNCATE delta_backfill;
    INSERT INTO delta_backfill
    SELECT
      m.id,
      m.app_version_id,
      av.app_id,
      m.s3_path,
      m.file_name,
      m.file_hash,
      COALESCE(m.file_size, 0),
      public.delta_path_key(m.s3_path),
      public.delta_entry_key(m.s3_path, m.file_name, m.file_hash)
    FROM public.manifest AS m
    INNER JOIN public.app_versions AS av ON av.id = m.app_version_id
    WHERE m.app_version_id = ANY (v_batch)
      AND m.s3_path IS NOT NULL AND m.file_name IS NOT NULL AND m.file_hash IS NOT NULL;
    GET DIAGNOSTICS v_batch_rows = ROW_COUNT;
    v_rows := v_rows + v_batch_rows;

    -- One row per unique entry; the largest known size wins, also against
    -- rows written by earlier batches.
    INSERT INTO public.delta_files AS df (app_id, s3_path, file_name, file_hash, file_size, path_key, entry_key)
    SELECT DISTINCT ON (b.entry_key)
      b.app_id, b.s3_path, b.file_name, b.file_hash, b.file_size, b.path_key, b.entry_key
    FROM delta_backfill AS b
    ORDER BY b.entry_key, b.file_size DESC
    ON CONFLICT (entry_key) DO UPDATE
    SET file_size = EXCLUDED.file_size
    WHERE df.file_size < EXCLUDED.file_size;

    -- The ordered file list of each version, in legacy row order. The id is
    -- a unique-index lookup per row: delta_files has no statistics yet, so a
    -- join could be planned as a scan of the whole table on every batch.
    INSERT INTO public.version_files (app_version_id, file_ids)
    SELECT
      b.app_version_id,
      pg_catalog.array_agg(
        (SELECT df.id FROM public.delta_files AS df WHERE df.entry_key = b.entry_key)
        ORDER BY b.id
      )
    FROM delta_backfill AS b
    GROUP BY b.app_version_id;

    RAISE NOTICE 'delta storage backfill: % of % versions, % rows, % s',
      LEAST(v_offset + v_batch_size, v_total), v_total, v_rows,
      pg_catalog.round(EXTRACT(EPOCH FROM pg_catalog.clock_timestamp() - v_started));
  END LOOP;
END;
$$;

-- Indexes are built once the rows are in.
CREATE INDEX delta_files_path_key_idx ON public.delta_files (path_key);
CREATE INDEX delta_files_app_id_idx ON public.delta_files (app_id);

-- Versions whose list only lives in the inline app_versions.manifest (no
-- legacy rows): same treatment, in list order.
CREATE TEMP TABLE delta_backfill_inline ON COMMIT DROP AS
SELECT
  av.id AS app_version_id,
  av.app_id,
  entry.ord,
  entry.s3_path::text AS s3_path,
  entry.file_name::text AS file_name,
  entry.file_hash::text AS file_hash,
  public.delta_path_key(entry.s3_path::text) AS path_key,
  public.delta_entry_key(entry.s3_path::text, entry.file_name::text, entry.file_hash::text) AS entry_key
FROM public.app_versions AS av
CROSS JOIN LATERAL pg_catalog.unnest(av.manifest) WITH ORDINALITY AS entry (file_name, s3_path, file_hash, ord)
WHERE av.manifest IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.version_files AS vf WHERE vf.app_version_id = av.id)
  AND entry.s3_path IS NOT NULL AND entry.file_name IS NOT NULL AND entry.file_hash IS NOT NULL;

INSERT INTO public.delta_files (app_id, s3_path, file_name, file_hash, file_size, path_key, entry_key)
SELECT DISTINCT ON (i.entry_key)
  i.app_id, i.s3_path, i.file_name, i.file_hash, 0, i.path_key, i.entry_key
FROM delta_backfill_inline AS i
ORDER BY i.entry_key
ON CONFLICT (entry_key) DO NOTHING;

INSERT INTO public.version_files (app_version_id, file_ids)
SELECT i.app_version_id, pg_catalog.array_agg(df.id ORDER BY i.ord)
FROM delta_backfill_inline AS i
INNER JOIN public.delta_files AS df ON df.entry_key = i.entry_key
GROUP BY i.app_version_id
ON CONFLICT (app_version_id) DO NOTHING;

-- Reverse lookup for GC. Primary only: excluded from the read-replica catalog.
CREATE INDEX version_files_file_ids_gin_idx ON public.version_files USING gin (file_ids);

COMMIT;

-- Statistics now, not at the next autovacuum: without them the planner treats
-- the new tables as empty and the first GC and update queries scan them.
-- ANALYZE does not block reads or writes.
ANALYZE public.delta_files, public.version_files;

RESET statement_timeout;
RESET lock_timeout;
